test_has_srctopic()
{
	local topic="${1}"
	test `find "${graderloc}/tests/" -name "${topic}-?.def" |wc -l` -gt 0
}

test_czar_result()
{
	local reg="${2}"
	local thisczr=./_${1%.def}-${reg}.czr
	local tokfile="${graderloc}/tests/${1%.def}.tok"
	local deffile="${graderloc}/tests/${1}"
	local expect="`find "${graderloc}" -name "${1%.def}.out"`"
	local exczr="${graderloc}/asm/${1%.def}-${reg}.czr"
	local tally="${3}/${1%.def}-${reg}"                  # where to keep grading tallies
	local thisresult="./_${1%.def}-${reg}.out"

	local seed="${expect%/*}"
	seed="${seed##*output-}"

	# removed when we touch good (if we don't exit prematurely
	touch "${tally}.bad"
	# will display error message on non-zero exit status
	if ! test_run "${comploc}/${PROGRAM}" "${reg}" "${tokfile}" "${deffile}" "${thisczr}" ; then
		if test ${GraderRunES} -ne 0 ; then
			return;
		fi
	fi
	# students love to not put newlines at the end of their last line of output... why?
	if ! test_run "${COMPGRADING}/emule" -s ${seed} -repl 10 -Nr ${regs%,*} -Nf ${regs#*,} <(cat "${thisczr}" ; echo ; echo ) |\
			"${COMPGRADING}/output-pipe" > ${thisresult} ; then 
		if test ${GraderRunES} -ne 0 ; then
			return;
		fi
	fi

	if ! diff -u "${thisresult}" "${expect}" 2>/dev/null > "_EMITTED.dif" ; then
		grader_msg <<EOT
OUTPUT lines generated by the  emule  emulator from your CZAR compiler don't
compare favorably to the expected output.  The original source is at
'${deffile%.def}.src' and its expected (emitted) output is at 
'${expect}'. The emitted output of your emulated assembler logic is at
'${thisresult}'. The output generated by your compiler is at 
'${thisczr}', you may want to compare it to the example assembler at
'${exczr}'.

A context diff of the emitted output comparisons is at _EMITTED.dif.

IMPORTANT: if the .src file has a  rand  instruction (and many do), then 
emule  runs your .czr instructions 10 times each with a different seed
(${seed}, ${seed}+1, ${seed}+2, ...).  The output you see are the concatenation
of these 10 runs.

CTRL-C now if you'd like to inspect these files.
EOT
		test -n "${GRADER_VIMDIFF}" && { vimdiff "${thisczr}" "${exczr}" ; sleep 1; }
		grader_keystroke
	else
		rm -f "${tally}.bad"
		touch "${tally}.good"
		grader_echo "OUTPUT lines for '${1}' look GOOD :)"
		echo
	fi
	return 0
}


test_gradermode_topic()
{
	case "${GRADERMODE:-UGRAD}/${1}" in
		*/intexpr|\
		*/fltexpr|\
		*/ifexpr|\
		*/cgldata\
			)  return 0 ;;
		ALL/loopexpr\
			) return 0 ;;
		* ) return 1 ;;
	esac
}

