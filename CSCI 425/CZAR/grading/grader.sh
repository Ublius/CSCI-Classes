declare -A TALLIESDESCR=( [intexpr]="int expressions and emit, rand int statements"
                         [fltexpr]="float expressions and emit, float float statements"
						 [ifexpr]="if-then, if-then-else control structures" 
						 [loopexpr]="do-while and while control structures"
						 [cgldata]="constant global literal data and emit string statements"
)

