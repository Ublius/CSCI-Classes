declare -A TALLYDIRS
# ugrad mode, no loops
CGLLI=5
test_gradermode_topic "intexpr"  && TALLYDIRS[intexpr]=`create_tally_dir  2 MAX=20 "${TALLIESDESCR[intexpr]}"`
test_gradermode_topic "fltexpr"  && TALLYDIRS[fltexpr]=`create_tally_dir  3 MAX=20 "${TALLIESDESCR[fltexpr]}"`
test_gradermode_topic "ifexpr"   && TALLYDIRS[ifexpr]=`create_tally_dir   4 MAX=5  "${TALLIESDESCR[ifexpr]}"`
if test_gradermode_topic loopexpr ; then 
	test_gradermode_topic "loopexpr" && TALLYDIRS[loopexpr]=`create_tally_dir 5 MAX=5  "${TALLIESDESCR[loopexpr]}"`
	CGLLI=6
fi
test_gradermode_topic "cgldata"  && TALLYDIRS[cgldata]=`create_tally_dir  ${CGLLI} MAX=5  "${TALLIESDESCR[cgldata]}"`

# test the appropriate .def files
for t in intexpr fltexpr ifexpr loopexpr cgldata ; do 
	test_gradermode_topic "${t}" || continue
	test_has_srctopic ${t} || continue
	for def in `( cd "${graderloc}/tests" && ls -1 ${t}*-?.def)` ; do 
		for regs in ${REGS} ; do 
			echo >&2 "test_czar_result" "${def}" ${regs} "${TALLYDIRS[${t}]}/*" 
#			continue
			#set -x
			test_czar_result "${def}" ${regs} "${TALLYDIRS[${t}]}" 
			set +x
		done
	done
done

